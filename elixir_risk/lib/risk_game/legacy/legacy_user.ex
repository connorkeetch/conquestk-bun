defmodule RiskGame.Legacy.User do
  @moduledoc """
  Legacy User schema mapping to the existing Node.js public.users table.
  This is READ-ONLY - used only for data migration and reading existing Node.js users.
  For new Elixir authentication, see RiskGame.Accounts.User generated by phx.gen.auth.
  """
  use Ecto.Schema
  import Ecto.Changeset

  # Use binary_id for UUID primary key
  @primary_key {:id, :binary_id, autogenerate: false}
  @foreign_key_type :binary_id

  # Map to the public.users table (not our elixir_risk schema)
  schema "users" do
    field :username, :string
    field :email, :string
    field :password_hash, :string
    field :skill_rating, :integer, default: 800
    field :is_admin, :boolean, default: false
    field :email_verified, :boolean, default: false
    field :verification_token, :string
    field :last_login, :utc_datetime
    field :timezone, :string
    field :preferred_language, :string, default: "en"
    field :marketing_consent, :boolean, default: false
    field :data_retention_consent, :boolean, default: true
    field :subscription_status, :string, default: "free"
    field :subscription_expires_at, :utc_datetime
    field :terms_accepted_at, :utc_datetime
    field :terms_version, :string
    field :privacy_accepted_at, :utc_datetime
    field :privacy_version, :string
    field :cookie_consent, :boolean, default: false
    field :cookie_consent_at, :utc_datetime
    field :is_vip, :boolean, default: false
    field :premium_tier, :string, default: "free"
    field :vip_granted_at, :utc_datetime
    field :vip_granted_by, :binary_id
    field :vip_reason, :string
    field :premium_expires_at, :utc_datetime
    field :is_beta_user, :boolean, default: false
    field :bio, :string
    field :deleted_at, :utc_datetime
    field :tagline, :string, default: "Commander of the Conquest Realms"
    field :ranked_wins, :integer, default: 0
    field :ranked_losses, :integer, default: 0
    field :highest_skill_rating, :integer, default: 800

    # Associations (will be added later)
    # has_many :game_memberships, RiskGame.Games.Player

    timestamps(type: :utc_datetime, inserted_at: :created_at, updated_at: :updated_at)
  end

  @doc """
  Read-only changeset for fetching users.
  We don't create/update users from the Elixir app.
  """
  def changeset(user, attrs) do
    user
    |> cast(attrs, [:username, :email, :skill_rating])
    |> validate_required([:username, :email])
  end
end
