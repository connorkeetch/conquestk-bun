declare let self: ServiceWorkerGlobalScope & typeof globalThis & { __WB_MANIFEST: unknown }

// Extend NotificationOptions with service-worker actions for better TS support
type SWNotificationAction = { action: string; title: string }
type SWNotificationOptions = NotificationOptions & { actions?: SWNotificationAction[] }

import { BackgroundSyncPlugin } from 'workbox-background-sync'
import { clientsClaim } from 'workbox-core'
import { ExpirationPlugin } from 'workbox-expiration'
import {
  cleanupOutdatedCaches,
  createHandlerBoundToURL,
  matchPrecache,
  precacheAndRoute,
} from 'workbox-precaching'
import { NavigationRoute, registerRoute, setCatchHandler } from 'workbox-routing'
import { CacheFirst, NetworkFirst, NetworkOnly, StaleWhileRevalidate } from 'workbox-strategies'

// Immediately activate the new SW and control uncontrolled clients
self.skipWaiting()
clientsClaim()

// Precache all assets generated by the build
// self.__WB_MANIFEST is injected at build time
// eslint-disable-next-line no-underscore-dangle
precacheAndRoute(self.__WB_MANIFEST)
cleanupOutdatedCaches()

// SPA navigation fallback to index.html (deny API)
const spaHandler = createHandlerBoundToURL('/index.html')
registerRoute(new NavigationRoute(spaHandler, { denylist: [/^\/api\//] }))

// Runtime caching: application assets
type RouteCtx = { request: Request; url: URL }

registerRoute(
  (ctx: RouteCtx) => ['script', 'style', 'worker'].includes(ctx.request.destination),
  new StaleWhileRevalidate({ cacheName: 'rk-assets' }),
)

// Images (local/CDN)
registerRoute(
  (ctx: RouteCtx) => ctx.request.destination === 'image',
  new StaleWhileRevalidate({
    cacheName: 'rk-images',
    plugins: [new ExpirationPlugin({ maxEntries: 200, maxAgeSeconds: 30 * 24 * 60 * 60 })],
  }),
)

// Fonts (Google fonts)
registerRoute(
  (ctx: RouteCtx) => ctx.request.destination === 'font' || ctx.url.hostname === 'fonts.gstatic.com',
  new CacheFirst({
    cacheName: 'rk-fonts',
    plugins: [new ExpirationPlugin({ maxEntries: 30, maxAgeSeconds: 365 * 24 * 60 * 60 })],
  }),
)

// CDN assets (map/audio) — adjust host as needed
registerRoute(
  (ctx: RouteCtx) => ctx.url.hostname === 'assets.conquestk.com',
  new StaleWhileRevalidate({
    cacheName: 'rk-cdn',
    plugins: [new ExpirationPlugin({ maxEntries: 200, maxAgeSeconds: 30 * 24 * 60 * 60 })],
  }),
)

// API GETs: cache-aside with network-first
registerRoute(
  (ctx: RouteCtx) => ctx.url.pathname.startsWith('/api/') && ctx.request.method === 'GET',
  new NetworkFirst({ cacheName: 'rk-api', networkTimeoutSeconds: 5 }),
)

// Background Sync: queue turn submissions when offline
// POST /api/game/rooms/:roomId/actions
const turnSubmitQueue = new BackgroundSyncPlugin('rk-turn-submissions', {
  maxRetentionTime: 24 * 60, // minutes (24h)
})

registerRoute(
  ({ url, request }: RouteCtx) =>
    request.method === 'POST' &&
    url.pathname.startsWith('/api/game/rooms/') &&
    url.pathname.endsWith('/actions'),
  new NetworkOnly({ plugins: [turnSubmitQueue] }),
  'POST',
)

// Background Sync: queue conquest transfer submissions
registerRoute(
  ({ url, request }: RouteCtx) =>
    request.method === 'POST' &&
    url.pathname.startsWith('/api/game/rooms/') &&
    url.pathname.endsWith('/transfer-conquest'),
  new NetworkOnly({ plugins: [turnSubmitQueue] }),
  'POST',
)

// Offline catch handler: return offline page for navigation requests
setCatchHandler(async (options: unknown) => {
  const event = (options as { event: FetchEvent }).event
  if (event.request.destination === 'document') {
    const offline = await matchPrecache('/offline.html')
    if (offline) return offline
    return Response.redirect('/')
  }
  return Response.error()
})

// Push notifications (ported from legacy sw.js)
self.addEventListener('push', (event: PushEvent) => {
  if (!event.data) return

  type PushPayload = {
    title?: string
    body?: string
    url?: string
    data?: Record<string, unknown>
    gameId?: string
    icon?: string
    badge?: string
    actions?: Array<{ action: string; title: string }>
    tag?: string
    renotify?: boolean
  }
  let notificationData: Partial<PushPayload> = {}
  try {
    notificationData = event.data.json() as Partial<PushPayload>
  } catch {
    notificationData = { title: 'ConquestK', body: event.data.text() }
  }

  const payloadData =
    typeof notificationData.data === 'object' && notificationData.data !== null
      ? notificationData.data
      : {}
  const purl = (payloadData as { url?: unknown }).url
  const targetUrl: string =
    typeof notificationData.url === 'string'
      ? notificationData.url
      : typeof purl === 'string'
        ? purl
        : '/'
  const mergedData = {
    ...payloadData,
    gameId: notificationData.gameId ?? payloadData.gameId,
    url: targetUrl,
    timestamp: new Date().toISOString(),
  }

  const options: SWNotificationOptions = {
    body: notificationData.body || 'You have a new notification',
    icon: notificationData.icon || '/icon-192.png',
    badge: notificationData.badge || '/icon-192.png',
    data: mergedData,
    tag: notificationData.tag || 'conquestk-notification',
  }

  // Pass through action buttons if provided by payload
  if (Array.isArray(notificationData.actions)) {
    const actions = notificationData.actions
      .filter(
        (a): a is SWNotificationAction =>
          a && typeof a.action === 'string' && typeof a.title === 'string',
      )
      .slice(0, 2)
    if (actions.length > 0) options.actions = actions
  }

  event.waitUntil(
    self.registration.showNotification(notificationData.title || 'ConquestK Notification', options),
  )
})

self.addEventListener('notificationclick', (event: NotificationEvent) => {
  event.notification.close()

  // If the user pressed an explicit close/decline action, do nothing further
  if (event.action === 'close') {
    return
  }

  const data = (event.notification.data || {}) as Record<string, unknown>
  let destination = '/'
  if (event.action === 'view' && data.gameId) {
    destination = `/game/${String(data.gameId)}`
  } else if (typeof data.url === 'string' && data.url.length > 0) {
    destination = data.url
  }

  let targetHref: string
  try {
    targetHref = new URL(destination, self.location.origin).href
  } catch {
    targetHref = self.location.origin
  }

  event.waitUntil(
    (async () => {
      const allClients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true })
      const targetOrigin = new URL(targetHref).origin
      for (const client of allClients) {
        try {
          const clientOrigin = new URL(client.url).origin
          if (clientOrigin === targetOrigin) {
            const win = client as WindowClient
            await win.focus()
            if (win.url !== targetHref) {
              try {
                await win.navigate(targetHref)
              } catch {
                // ignore navigate errors and fall back to openWindow
              }
            }
            return
          }
        } catch {
          // ignore invalid client URLs
        }
      }
      await self.clients.openWindow(targetHref)
    })(),
  )
})
